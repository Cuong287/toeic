export function cleanWordKey(w) {
  return String(w || '')
    .toLowerCase()
    .replace(/[()]/g, '')
    .replace(/^be\s+/i, '')
    .replace(/\s+/g, ' ')
    .trim();
}

export function getWordClue(word, topicId, vObj) {
  if (!word) return '';
  const key = cleanWordKey(word);
  if (VOCAB_CLUES[key]) return VOCAB_CLUES[key];

  const rawKey = String(word).trim().toLowerCase();
  if (VOCAB_CLUES[rawKey]) return VOCAB_CLUES[rawKey];

  for (const [k, clue] of Object.entries(VOCAB_CLUES)) {
    if (k.length > 3 && (key === k || key.startsWith(k + ' ') || k.startsWith(key + ' '))) {
      return clue;
    }
  }

  if (vObj && vObj.pos) {
    const posMap = {
      n: 'A noun referring to a key concept or item in this topic.',
      v: 'A verb meaning to perform an action related to this topic.',
      a: 'An adjective describing a condition or quality in this topic.',
      adj: 'An adjective describing a condition or quality in this topic.',
      adv: 'An adverb describing how an action is performed.'
    };
    return posMap[vObj.pos] || 'A key term in this topic.';
  }
  return 'A key vocabulary term in this topic.';
}
