// Backward-compatible alias
export const VOCAB_CLUES = VOCAB_CLUES_VI;

export function cleanWordKey(w) {
  return String(w || '')
    .toLowerCase()
    .replace(/[()]/g, '')
    .replace(/^be\s+/i, '')
    .replace(/\s+/g, ' ')
    .trim();
}

export function getWordClue(word, topicId, vObj, lang = 'vi') {
  if (!word) return '';
  const key = cleanWordKey(word);
  const dict = lang === 'en' ? VOCAB_CLUES_EN : VOCAB_CLUES_VI;
  if (dict[key]) return dict[key];

  const rawKey = String(word).trim().toLowerCase();
  if (dict[rawKey]) return dict[rawKey];

  for (const [k, clue] of Object.entries(dict)) {
    if (k.length > 3 && (key === k || key.startsWith(k + ' ') || k.startsWith(key + ' '))) {
      return clue;
    }
  }

  const altDict = lang === 'en' ? VOCAB_CLUES_VI : VOCAB_CLUES_EN;
  if (altDict[key]) return altDict[key];

  if (vObj && vObj.pos) {
    if (lang === 'vi') {
      const posMapVi = {
        n: 'Danh từ chỉ khái niệm, sự vật hoặc đối tượng quan trọng trong chủ đề này.',
        v: 'Động từ chỉ hành động, thao tác hoặc quy trình trong chủ đề này.',
        a: 'Tính từ mô tả tính chất, đặc điểm hoặc trạng thái trong chủ đề này.',
        adj: 'Tính từ mô tả tính chất, đặc điểm hoặc trạng thái trong chủ đề này.',
        adv: 'Trạng từ diễn tả cách thức hoặc mức độ của hành động.'
      };
      return posMapVi[vObj.pos] || 'Thuật ngữ cốt lõi trong chủ đề này.';
    } else {
      const posMapEn = {
        n: 'A noun referring to a key concept or item in this topic.',
        v: 'A verb meaning to perform an action related to this topic.',
        a: 'An adjective describing a condition or quality in this topic.',
        adj: 'An adjective describing a condition or quality in this topic.',
        adv: 'An adverb describing how an action is performed.'
      };
      return posMapEn[vObj.pos] || 'A key term in this topic.';
    }
  }
  return lang === 'vi' ? 'Thuật ngữ từ vựng trọng tâm trong chủ đề này.' : 'A key vocabulary term in this topic.';
}
